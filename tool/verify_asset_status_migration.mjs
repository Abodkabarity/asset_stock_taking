// Install test-only PostgreSQL/WASM in build/status-db-validation, then run:
// node tool/verify_asset_status_migration.mjs
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '../build/status-db-validation/node_modules/@electric-sql/pglite/dist/index.js';

const db = new PGlite();
await db.exec(`
  create table public.asset_stock_taking (
    id bigint generated by default as identity primary key,
    item_code text unique not null, status text not null, location text default 'Store',project_name text default '');
  create table public.asset_stock_taking_deleted (id bigint, item_code text, status text);
  create table public.asset_checkouts (
    id bigint generated by default as identity primary key, item_code text,
    original_status text, is_checked_in boolean default false,
    checked_out_at timestamptz default now());
  create table public.asset_reservations (
    id bigint generated by default as identity primary key, item_code text,
    original_status text, is_active boolean default true,
    reserved_at timestamptz default now(),target_location text default 'Dubai',released_at timestamptz,resolution text);
  create table public.asset_maintenance (
    id bigint generated by default as identity primary key, item_code text,
    status text default 'Open');
  create table public.asset_activity_log (
    id bigint generated by default as identity primary key, item_code text,
    action text, metadata jsonb default '{}', created_at timestamptz default now());
  create table public.app_audit_log (
    id bigint generated by default as identity primary key,
    entity_table text,operation text,item_code text,old_data jsonb,new_data jsonb,
    occurred_at timestamptz default now());
  create role authenticated;
  insert into public.asset_stock_taking(item_code,status) values
    ('good','Good'),('damaged','Damaged'),('reserved','Reserved'),
    ('unknown','Maintenance'),('disposed','Disposed'),('custom','Refurbished'),
    ('checkout','Checked Out'),('parallel-maintenance','Bad'),('stale-evidence','Disposed'),
    ('audit-recovered','Maintenance');
  insert into public.app_audit_log(entity_table,operation,item_code,old_data,new_data)
    values ('asset_stock_taking','UPDATE','audit-recovered','{"status":"Damaged"}','{"status":"Maintenance"}');
  insert into public.asset_reservations(item_code,original_status) values ('reserved','Damaged');
  insert into public.asset_checkouts(item_code,original_status) values ('checkout','Very Good');
  insert into public.asset_activity_log(item_code,action,metadata) values
    ('disposed','dispose_status','{"previous_status":"New"}'),
    ('stale-evidence','dispose_status','{"previous_status":"Good"}'),
    ('stale-evidence','dispose_status','{}');
`);
const migration = await readFile(new URL(
  '../supabase/migrations/20261016100108_separate_asset_condition_and_operations.sql', import.meta.url), 'utf8');
await db.exec(migration);

let checks = 0;
async function expectState(code, condition, operation) {
  const { rows } = await db.query('select status,operational_status from public.asset_stock_taking where item_code=$1', [code]);
  assert.deepEqual(rows, [{ status: condition, operational_status: operation }]);
  checks++;
}
await expectState('reserved', 'Damaged', 'Reserved');
await expectState('checkout', 'Very Good', 'Checked Out');
await expectState('unknown', 'Unknown', 'Maintenance');
await expectState('disposed', 'New', 'Disposed');
await expectState('custom', 'Refurbished', 'Available');
await expectState('stale-evidence', 'Unknown', 'Disposed');
await expectState('audit-recovered', 'Damaged', 'Maintenance');
assert.equal((await db.query("select legacy_status_before_separation from public.asset_stock_taking where item_code='unknown'")).rows[0].legacy_status_before_separation, 'Maintenance');

await db.exec("insert into public.asset_checkouts(item_code,original_status) values ('damaged','Damaged')");
await expectState('damaged', 'Damaged', 'Checked Out');
await assert.rejects(db.exec("insert into public.asset_reservations(item_code) values ('damaged')"), /no longer available/);
assert.equal((await db.query("select count(*)::integer n from public.asset_reservations where item_code='damaged'")).rows[0].n, 0);
checks++;
await db.exec("update public.asset_checkouts set is_checked_in=true where item_code='damaged'");
await expectState('damaged', 'Damaged', 'Available');
await db.exec("update public.asset_reservations set is_active=false where item_code='reserved'");
await expectState('reserved', 'Damaged', 'Available');
await db.exec("insert into public.asset_reservations(item_code,original_status) values ('reserved','Good')");
await db.exec("select public.asset_transfer_reservation((select max(id) from public.asset_reservations where item_code='reserved'))");
await expectState('reserved','Damaged','Available');
assert.equal((await db.query("select location from public.asset_stock_taking where item_code='reserved'")).rows[0].location,'Dubai');

await db.exec("insert into public.asset_maintenance(item_code,status) values ('parallel-maintenance','Open'),('parallel-maintenance','In Progress')");
await expectState('parallel-maintenance', 'Bad', 'Maintenance');
await db.exec("update public.asset_maintenance set status='Completed' where id=(select min(id) from public.asset_maintenance where item_code='parallel-maintenance')");
await expectState('parallel-maintenance', 'Bad', 'Maintenance');
await db.exec("update public.asset_maintenance set status='Closed' where item_code='parallel-maintenance'");
await expectState('parallel-maintenance', 'Bad', 'Available');
await db.exec("insert into public.asset_maintenance(item_code,status) values ('unknown','Completed')");
await expectState('unknown', 'Unknown', 'Available');
await db.exec("update public.asset_stock_taking set operational_status='Disposed' where item_code='damaged'");
await expectState('damaged', 'Damaged', 'Disposed');
await assert.rejects(db.exec("update public.asset_stock_taking set operational_status='Available' where item_code='damaged'"), /cannot be reactivated/);
checks++;

// Compatibility guard translates old operation markers without losing condition.
await db.exec("update public.asset_stock_taking set status='Under Maintenance' where item_code='good'");
await expectState('good', 'Good', 'Maintenance');
await db.exec("update public.asset_stock_taking set status='Damaged',condition_revision=1 where item_code='good'");
await expectState('good', 'Damaged', 'Maintenance');
await assert.rejects(db.exec("update public.asset_stock_taking set status='Good' where item_code='good'"), /explicit confirmation/);
await expectState('good','Damaged','Maintenance');
await assert.rejects(db.exec("update public.asset_stock_taking set status='Good',condition_revision=1 where item_code='good'"), /explicit confirmation/);
await expectState('good','Damaged','Maintenance');

// Trigger invokers work with the same table rights as the app, without EXECUTE
// grants or privileged SECURITY DEFINER functions.
await db.exec(`
  create role workflow_client;
  grant usage on schema public to workflow_client;
  grant select,update on public.asset_stock_taking to workflow_client;
  grant select,insert,update on public.asset_checkouts,public.asset_reservations,public.asset_maintenance to workflow_client;
  grant usage,select on all sequences in schema public to workflow_client;
  set role workflow_client;
  insert into public.asset_checkouts(item_code,original_status) values ('custom','Refurbished');
`);
await expectState('custom', 'Refurbished', 'Checked Out');
await db.exec('reset role');
await db.close();
console.log(`PostgreSQL migration verified: ${checks} state and recovery checks passed.`);
